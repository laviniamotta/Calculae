BEGIN;

-- 1. TABELAS

CREATE TABLE public.commission_ranges (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id uuid NOT NULL,
  min_sales numeric(12, 2) NOT NULL DEFAULT 0,
  max_sales numeric(12, 2),
  commission_rate numeric(5, 2) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commission_ranges_pkey PRIMARY KEY (id),
  CONSTRAINT commission_ranges_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE,
  CONSTRAINT commission_ranges_rate_valid
    CHECK (commission_rate >= 0 AND commission_rate <= 100),
  CONSTRAINT commission_ranges_max_valid
    CHECK (max_sales IS NULL OR max_sales > min_sales),
  CONSTRAINT commission_ranges_min_nonnegative
    CHECK (min_sales >= 0)
);

CREATE TABLE public.sales_entries (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL,
  sale_date date NOT NULL DEFAULT CURRENT_DATE,
  entry_type text NOT NULL,
  amount numeric(12, 2) NOT NULL,
  quantity integer NOT NULL DEFAULT 1,
  description text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT sales_entries_pkey PRIMARY KEY (id),
  CONSTRAINT sales_entries_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE,
  CONSTRAINT sales_entries_quantity_check CHECK (quantity > 0),
  CONSTRAINT sales_entries_entry_type_check
    CHECK (entry_type IN ('individual', 'daily_total')),
  CONSTRAINT sales_entries_amount_check CHECK (amount > 0)
);

CREATE TABLE public.user_settings (
  user_id uuid NOT NULL,
  commission_rate numeric(5, 2) NOT NULL DEFAULT 0,
  monthly_goal numeric(12, 2) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  company_name text NOT NULL DEFAULT '',
  professional_name text NOT NULL DEFAULT '',
  job_title text NOT NULL DEFAULT '',
  base_salary numeric(12, 2) NOT NULL DEFAULT 0,
  transport_allowance numeric(12, 2) NOT NULL DEFAULT 0,
  other_benefits numeric(12, 2) NOT NULL DEFAULT 0,
  fixed_deductions numeric(12, 2) NOT NULL DEFAULT 0,
  vacation_days_available integer NOT NULL DEFAULT 30,
  vacation_days_planned integer NOT NULL DEFAULT 0,
  vacation_start_date date,
  vacation_end_date date,
  notes text NOT NULL DEFAULT '',
  currency_code text NOT NULL DEFAULT 'BRL',
  admission_date date,
  vacation_taken_this_year boolean NOT NULL DEFAULT false,
  vacation_checked_year integer NOT NULL
    DEFAULT (EXTRACT(year FROM CURRENT_DATE)::integer),
  vacation_mode_enabled boolean NOT NULL DEFAULT false,
  vacation_mode_start_date date,
  vacation_mode_end_date date,

  CONSTRAINT user_settings_pkey PRIMARY KEY (user_id),
  CONSTRAINT user_settings_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE,
  CONSTRAINT user_settings_base_salary_nonnegative
    CHECK (base_salary >= 0),
  CONSTRAINT user_settings_benefits_nonnegative
    CHECK (other_benefits >= 0),
  CONSTRAINT user_settings_commission_rate_check
    CHECK (commission_rate >= 0 AND commission_rate <= 100),
  CONSTRAINT user_settings_commission_rate_range
    CHECK (commission_rate >= 0 AND commission_rate <= 100),
  CONSTRAINT user_settings_deductions_nonnegative
    CHECK (fixed_deductions >= 0),
  CONSTRAINT user_settings_monthly_goal_check
    CHECK (monthly_goal >= 0),
  CONSTRAINT user_settings_monthly_goal_nonnegative
    CHECK (monthly_goal >= 0),
  CONSTRAINT user_settings_transport_nonnegative
    CHECK (transport_allowance >= 0),
  CONSTRAINT user_settings_vacation_available_range
    CHECK (vacation_days_available BETWEEN 0 AND 365),
  CONSTRAINT user_settings_vacation_planned_range
    CHECK (vacation_days_planned BETWEEN 0 AND 365)
);

-- 2. ÍNDICES

CREATE INDEX sales_entries_user_date_idx
  ON public.sales_entries USING btree (user_id, sale_date DESC);

-- 3. FUNÇÃO E TRIGGER EXISTENTES
-- Somente user_settings possui esse trigger no inventário atual.

CREATE OR REPLACE FUNCTION public.calculae_settings_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$function$;

CREATE TRIGGER calculae_settings_updated_at
  BEFORE UPDATE ON public.user_settings
  FOR EACH ROW
  EXECUTE FUNCTION public.calculae_settings_set_updated_at();

-- 4. RLS

ALTER TABLE public.commission_ranges ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sales_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_settings ENABLE ROW LEVEL SECURITY;

-- commission_ranges

CREATE POLICY "Users can delete own commission ranges"
  ON public.commission_ranges
  FOR DELETE TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY "Users can view own commission ranges"
  ON public.commission_ranges
  FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY "Users can update own commission ranges"
  ON public.commission_ranges
  FOR UPDATE TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can insert own commission ranges"
  ON public.commission_ranges
  FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);

-- sales_entries
-- No banco atual, estas quatro policies estão atribuídas a PUBLIC.

CREATE POLICY "Users can insert their own sales"
